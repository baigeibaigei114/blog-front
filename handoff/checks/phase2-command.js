async page=>{
  const ensure=(value,message)=>{if(!value)throw Error(message)},passed=[]
  const base='http://127.0.0.1:5173/blog-front'
  await page.goto(base+'/admin/studio?tab=inbox')
  if(await page.getByLabel('管理员密码').isVisible()){await page.getByLabel('管理员密码').fill('devblog-mock');await page.getByRole('button',{name:'登录工作台 ↗'}).click()}
  await page.getByRole('button',{name:'＋ 录入片段'}).waitFor()
  await page.keyboard.press('Control+k')
  await page.getByRole('combobox',{name:'搜索文章、日志或页面'}).fill('录入学习片段')
  await page.keyboard.press('Enter')
  await page.getByRole('dialog',{name:'录入学习片段'}).waitFor()
  ensure(new URL(page.url()).searchParams.get('action')==='import','Command did not route to import')
  await page.keyboard.press('Escape')
  await page.getByRole('dialog',{name:'录入学习片段'}).waitFor({state:'hidden'})
  await page.waitForURL(url=>!url.searchParams.has('action'))
  ensure(!new URL(page.url()).searchParams.has('action'),'Import action query not cleared')
  await page.keyboard.press('Control+k')
  await page.getByRole('combobox',{name:'搜索文章、日志或页面'}).fill('发布设置')
  await page.keyboard.press('Enter');await page.getByLabel('每日整理时间').waitFor()
  await page.keyboard.press('Control+k')
  await page.getByRole('combobox',{name:'搜索文章、日志或页面'}).fill('查看发布记录')
  await page.keyboard.press('Enter');await page.getByRole('button',{name:'刷新记录',exact:true}).waitFor()
  passed.push('Admin command routing to import, settings and run history; import action cleared on close')
  await page.goto(base+'/admin/studio?tab=invalid')
  await page.waitForURL('**/admin/studio?tab=inbox')
  await page.getByRole('button',{name:'＋ 录入片段'}).waitFor()
  await page.evaluate(()=>window.confirm=()=>true)
  await page.getByRole('button',{name:'退出登录',exact:true}).click()
  await page.getByLabel('管理员密码').waitFor()
  await page.keyboard.press('Control+k')
  await page.getByRole('combobox',{name:'搜索文章、日志或页面'}).fill('录入学习片段')
  ensure(await page.getByRole('option').filter({hasText:'录入学习片段'}).count()===0,'Anonymous command exposed admin action')
  await page.keyboard.press('Escape')
  passed.push('Invalid studio tab normalized; logout removes admin commands')
  return JSON.stringify({suite:'phase2-command-mock',passed})
}
